import * as fs from 'fs'
import * as path from 'path'

// Lambda@Edge does not allow environment variables: synth fails with
// LambdaEdgeEnvironmentVariablesNotAllowed the moment an edge function declares one, and the
// suggested `removeInEdge` escape hatch only strips the variable at the edge - which is precisely
// where the injector needs it. So the media bucket name travels inside the code asset instead:
// this file is written during synth, immediately before Code.fromAsset hashes the folder, so a
// change of bucket produces a new function version on its own.
//
// It is generated into the injector's own folder because that folder is deployed as a raw zip and
// cannot import anything from outside it - the same constraint that keeps mediaNaming.js self
// contained. The reader beside it (bucket.js) prefers an explicit WISAW_IMG_BUCKET, which is what
// lets tests and a local run pick their own bucket without touching this file.

/** Name of the generated file inside the injector's asset folder. */
export const EDGE_BUCKET_FILE = 'bucket.gen.js'

function quote (value: string): string {
  return `'${value.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`
}

/** Contents of the generated module. Pure, so a test can pin the exact bytes. */
export function edgeBucketModuleSource (bucket: string): string {
  return `/* eslint-env node */
/* global module */

// GENERATED by lib/utilities/edgeMediaBucket.ts during \`cdk synth\` - do not edit, and do not
// commit: it is .gitignored, because the bucket belongs to whichever environment is being
// deployed. Lambda@Edge rejects environment variables, so this is how the injector learns which
// bucket holds the media and its <id>.json sidecars.

module.exports = { BUCKET: ${quote(bucket)} }
`
}

/**
 * Writes the generated module into `folder` unless it already says exactly this, and returns the
 * path. Writing only on change keeps the asset hash - and therefore the deployed function version -
 * stable across repeated synths of the same environment.
 */
export function writeEdgeBucketConfig (folder: string, bucket: string): string {
  const value = String(bucket ?? '').trim()
  if (value === '') {
    throw new Error('cannot configure the edge media bucket: S3_BUCKET is missing from the deployed environment (.env.<env>)')
  }

  const target = path.join(folder, EDGE_BUCKET_FILE)
  const source = edgeBucketModuleSource(value)
  if (fs.existsSync(target) && fs.readFileSync(target, 'utf8') === source) return target

  fs.writeFileSync(target, source)
  return target
}
